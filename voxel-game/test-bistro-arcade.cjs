const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {chromium}=require('playwright');

(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1100,height:700}});
  const root=path.resolve(__dirname,'../client/public/static/games');
  await page.route('https://kitt-franco-belge.be/static/games/**',route=>{const pathname=new URL(route.request().url()).pathname,base=path.resolve(root,pathname.replace('/static/games/','')),local=fs.existsSync(base)&&fs.statSync(base).isDirectory()?path.join(base,'index.html'):base;if(local.startsWith(root+path.sep)&&fs.existsSync(local)&&fs.statSync(local).isFile())return route.fulfill({path:local});return route.continue()});
  const hubFile='file:///'+path.resolve(root,'kitt-arcade/index.html').replace(/\\/g,'/');
  await page.goto(hubFile);
  assert.equal(await page.locator('.game').count(),10,'Le catalogue local doit afficher ses dix jeux.');
  await page.locator('#gameSearch').fill('snake');
  assert.equal(await page.locator('.game:not(.hidden-game)').count(),1,'La recherche doit isoler Circuit Snake.');
  await page.locator('#gameFilter').selectOption('LOGIQUE');
  assert.equal(await page.locator('.game:not(.hidden-game)').count(),0,'La recherche et le filtre doivent se combiner.');
  await page.locator('#gameSearch').fill('');
  assert.equal(await page.locator('.game:not(.hidden-game)').count(),1,'Le filtre logique doit isoler le Démineur.');
  await page.locator('#gameFilter').selectOption('all');
  await page.locator('#gameSearch').fill('introuvable');
  assert.equal(await page.locator('#noGames').isVisible(),true,'Une recherche vide doit expliquer clairement le résultat.');
  await page.locator('#gameSearch').fill('');
  await page.setViewportSize({width:390,height:844});
  await page.goto(hubFile);
  assert.ok(await page.locator('#gameSearch').isVisible(),'La recherche reste accessible sur mobile.');
  assert.ok(await page.locator('.game').first().isVisible(),'Les cartes restent jouables sur mobile.');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Le catalogue mobile ne doit pas déborder horizontalement.');
  await page.setViewportSize({width:1100,height:700});
  const snakeFile='file:///'+path.resolve(root,'kitt-arcade/games/circuit-snake/index.html').replace(/\\/g,'/');
  await page.goto(snakeFile);
  assert.equal(await page.locator('#kittArcadeSound').getAttribute('aria-pressed'),'true','Les effets sonores synthétiques démarrent activés.');
  await page.locator('#kittArcadeSound').click();
  assert.equal(await page.locator('#kittArcadeSound').getAttribute('aria-pressed'),'false','Le bouton coupe réellement les effets.');
  await page.locator('#kittArcadeSound').click();
  assert.equal(await page.locator('#kittArcadeSound').getAttribute('aria-pressed'),'true','Le bouton réactive réellement les effets.');
  await page.goto('https://kitt-franco-belge.be/static/games/kitt-arcade/index.html');
  assert.equal(await page.locator('.game').count(),10,'Le kiosque doit présenter ses dix jeux.');
  await page.evaluate(()=>{localStorage.removeItem('kitt-arcade-last-game');localStorage.removeItem('kittArcade.snake.best')});
  await page.locator('.game').first().click();
  assert.ok(await page.locator('#board').count(),'Le clic sur une carte lance bien son jeu.');
  await page.goBack();
  assert.equal(await page.locator('#resumeGame').isEnabled(),true,'Le bouton reprend le dernier jeu lancé.');
  assert.match(await page.locator('#resumeGame').textContent(),/CIRCUIT SNAKE/);
  await page.evaluate(()=>localStorage.setItem('kittArcade.snake.best','42'));
  await page.reload();
  assert.equal(await page.locator('.game').first().locator('.game-best').textContent(),'Record 42','Le carnet montre le record local à côté du jeu.');
  assert.match(await page.locator('#progressNote').textContent(),/1\/10 jeux avec un record/);
  await page.goto('https://kitt-franco-belge.be/static/games/kitt-stunt/index.html');
  await page.locator('#start').click();
  assert.equal(await page.locator('#title').evaluate(e=>e.classList.contains('hidden')),true,'Le bouton doit démarrer la course.');
  const before=await page.locator('#distance').textContent();
  await page.keyboard.press('Space');
  await page.waitForTimeout(900);
  const after=await page.locator('#distance').textContent();
  assert.notEqual(after,before,'La distance doit progresser pendant la course.');
  assert.ok(await page.locator('#game').evaluate(c=>c.width===960&&c.height===540),'La scène Canvas doit être initialisée.');
  assert.ok(fs.existsSync(path.join(root,'space_invaders_pro','index.html')),'La borne Space Invaders doit utiliser le jeu installé du site.');
  console.log('OK Chrome : recherche/filtres, sons synthétiques, reprise du dernier jeu, records locaux, dix jeux et Stunt jouable.');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
